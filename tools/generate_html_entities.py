#!/usr/bin/env python3
"""Generate the pure-Bend HTML5 named-entity lookup table."""

import argparse
import hashlib
import json
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = "https://html.spec.whatwg.org/entities.json"
SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"
EXPECTED_ENTRIES = 2231
EXPECTED_SEMICOLON_ENTRIES = 2125
MAX_GROUP_ENTRIES = 256


def fetch():
    with urllib.request.urlopen(URL, timeout=30) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"entities.json sha256 changed: {digest}")
    table = json.loads(data)
    if len(table) != EXPECTED_ENTRIES:
        raise SystemExit(f"expected {EXPECTED_ENTRIES} entries, found {len(table)}")
    return table


def bend_escape(text):
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        else:
            out.append(char)
    return "".join(out)


PRELUDE = '''# Generated by tools/generate_html_entities.py.
# Source: https://html.spec.whatwg.org/entities.json
# Source SHA-256: d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6
# Do not edit by hand.

import Base

def ifs(-A: Type, z: Bool, yes: Unit -> A, no: Unit -> A) -> A:
  match z:
    case True{}:
      yes(Unit{})
    case False{}:
      no(Unit{})

type HtmlEntityNameScan is Data:
  HtmlEntityNameScan{name: String, rest: String}

def html_entity_name_scan_name(x: HtmlEntityNameScan) -> String:
  match x:
    case HtmlEntityNameScan{name, rest}:
      name

def html_entity_name_scan_rest(x: HtmlEntityNameScan) -> String:
  match x:
    case HtmlEntityNameScan{name, rest}:
      rest

def html_entity_scan_name_go(s: String, +acc: String) -> HtmlEntityNameScan:
  match s:
    case SNil{}:
      HtmlEntityNameScan{String.reverse(acc), SNil{}}
    case SCon{'=', t}:
      HtmlEntityNameScan{String.reverse(acc), t}
    case SCon{+h, +t}:
      html_entity_scan_name_go(t, SCon{h, acc})

def html_entity_scan_name(+s: String) -> HtmlEntityNameScan:
  html_entity_scan_name_go(s, SNil{})

type HtmlEntityLenScan is Data:
  HtmlEntityLenScan{count: Nat, rest: String}

def html_entity_len_scan_count(x: HtmlEntityLenScan) -> Nat:
  match x:
    case HtmlEntityLenScan{count, rest}:
      count

def html_entity_len_scan_rest(x: HtmlEntityLenScan) -> String:
  match x:
    case HtmlEntityLenScan{count, rest}:
      rest

def html_entity_scan_len_go(s: String, +value: Nat) -> HtmlEntityLenScan:
  match s:
    case SCon{':', t}:
      HtmlEntityLenScan{value, t}
    case SCon{+h, +t}:
      html_entity_scan_len_go(t, Nat.add(Nat.mul(value, 10n),
        Nat.sub(U32.to_nat(Char.to_u32(h)), 48n)))
    case SNil{}:
      HtmlEntityLenScan{value, SNil{}}

def html_entity_scan_len(+s: String) -> HtmlEntityLenScan:
  html_entity_scan_len_go(s, 0n)

type HtmlEntityValueScan is Data:
  HtmlEntityValueScan{decoded: String, rest: String}

def html_entity_value_scan_decoded(x: HtmlEntityValueScan) -> String:
  match x:
    case HtmlEntityValueScan{decoded, rest}:
      decoded

def html_entity_value_scan_rest(x: HtmlEntityValueScan) -> String:
  match x:
    case HtmlEntityValueScan{decoded, rest}:
      rest

def html_entity_take_value_finish(s: String, +acc: String) -> HtmlEntityValueScan:
  match s:
    case SCon{';', t}:
      HtmlEntityValueScan{String.reverse(acc), t}
    case u:
      HtmlEntityValueScan{String.reverse(acc), u}

def html_entity_take_value_go(s: String, n: Nat, +acc: String) -> HtmlEntityValueScan:
  match s n:
    case SNil{} _:
      HtmlEntityValueScan{String.reverse(acc), SNil{}}
    case SCon{+h, +t} 1n++p:
      html_entity_take_value_go(t, p, SCon{h, acc})
    case SCon{+h, +t} 0n:
      html_entity_take_value_finish(t, acc)

def html_entity_scan_value(+s: String) -> HtmlEntityValueScan:
  +lenscan = html_entity_scan_len(s)
  html_entity_take_value_go(html_entity_len_scan_rest(lenscan),
    html_entity_len_scan_count(lenscan), SNil{})

def html_entity_lookup_encoded_go(fuel: Nat, +table: String, +name: String) -> Maybe<&2, String>:
  match fuel:
    case 0n:
      None{}
    case 1n++f:
      match table:
        case SNil{}:
          None{}
        case SCon{+h0, +t0}:
          +namescan = html_entity_scan_name(table)
          +valuescan = html_entity_scan_value(html_entity_name_scan_rest(namescan))
          ifs(Maybe<&2, String>, String.eq(name, html_entity_name_scan_name(namescan)),
            u => Some{html_entity_value_scan_decoded(valuescan)},
            u => html_entity_lookup_encoded_go(f, html_entity_value_scan_rest(valuescan), name))

def html_entity_lookup_encoded(+table: String, +name: String) -> Maybe<&2, String>:
  html_entity_lookup_encoded_go(256n, table, name)

'''


def render(entries):
    groups = defaultdict(list)
    for name, characters in entries:
        groups[name[0]].append((name, characters))
    if max(len(items) for items in groups.values()) >= MAX_GROUP_ENTRIES:
        raise SystemExit("entity group exceeds lookup fuel")

    out = [PRELUDE]
    for first in sorted(groups):
        function_name = "html5_entity_table_" + first + ("_upper" if first.isupper() else "")
        body = "".join(
            f"{name}={len(characters)}:{bend_escape(characters)};"
            for name, characters in groups[first]
        )
        out.append(f"def {function_name}() -> String:\n")
        out.append(f"  \"{body}\"\n\n")

    out.append("# Lookup for HTML5 named entity references that end in a semicolon.  The\n")
    out.append("# keys are the authoritative names without the leading ampersand and\n")
    out.append("# trailing semicolon because Markdown scanning has already consumed both.\n")
    out.append("def html5_named_entity_value(+name: String) -> Maybe<&2, String>:\n")
    out.append("  match name:\n")
    for first in sorted(groups):
        function_name = "html5_entity_table_" + first + ("_upper" if first.isupper() else "")
        out.append(f"    case SCon{{'{first}', t}}:\n")
        out.append(f"      html_entity_lookup_encoded({function_name}(), name)\n")
    out.append("    case u:\n")
    out.append("      None{}\n")
    return "".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(ROOT / "src/html_entities.bend"))
    args = parser.parse_args()

    table = fetch()
    entries = []
    seen = set()
    for key, value in table.items():
        if not key.endswith(";"):
            continue
        name = key[1:-1]
        if name in seen:
            raise SystemExit(f"duplicate semicolon entity name: {name}")
        seen.add(name)
        entries.append((name, value["characters"]))
    if len(entries) != EXPECTED_SEMICOLON_ENTRIES:
        raise SystemExit(f"expected {EXPECTED_SEMICOLON_ENTRIES} semicolon entries, found {len(entries)}")
    entries.sort()
    output = Path(args.output)
    output.write_text(render(entries), encoding="utf-8")
    print(f"wrote {output} ({len(entries)} entities)")


if __name__ == "__main__":
    main()
