#!/usr/bin/env python3
"""Generate the pure-Bend Unicode full-case-folding lookup table."""

import argparse
import hashlib
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = "https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt"
SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"
EXPECTED_ENTRIES = 1585
MAX_BUCKET_ENTRIES = 160


def fetch():
    with urllib.request.urlopen(URL, timeout=30) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"CaseFolding.txt sha256 changed: {digest}")
    return data.decode("utf-8")


def parse(text):
    mappings = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [part.strip() for part in line.split(";")]
        if len(parts) < 4 or parts[1] not in {"C", "F"}:
            continue
        codepoint = int(parts[0], 16)
        folded = "".join(chr(int(piece, 16)) for piece in parts[2].split())
        if codepoint in mappings and mappings[codepoint] != folded:
            raise SystemExit(f"conflicting case folds for U+{codepoint:04X}")
        mappings[codepoint] = folded
    if len(mappings) != EXPECTED_ENTRIES:
        raise SystemExit(f"expected {EXPECTED_ENTRIES} full-fold entries, found {len(mappings)}")
    return sorted(mappings.items())


def bend_escape(text):
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        else:
            out.append(char)
    return "".join(out)


PRELUDE = '''# Generated by tools/generate_unicode_casefold.py.
# Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt
# Source SHA-256: ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183
# Do not edit by hand.
#
# The table combines the authoritative C and F mappings and deliberately
# excludes Turkic T mappings, as required for language-independent full case
# folding.  Entries are sorted in each 256-code-point bucket and encoded as
# six hex digits, one length digit, a colon, the folded text, and a semicolon.

import Base

def ifs(-A: Type, z: Bool, yes: Unit -> A, no: Unit -> A) -> A:
  match z:
    case True{}:
      yes(Unit{})
    case False{}:
      no(Unit{})

def maybe_case(-A: Data, -B: Type, m: Maybe<&2, A>, some: A -> B, none: Unit -> B) -> B:
  match m:
    case Some{x}:
      some(x)
    case None{}:
      none(Unit{})

type UcfHexScan is Data:
  UcfHexScan{value: U32, rest: String}

def ucf_hex_scan_value(x: UcfHexScan) -> U32:
  match x:
    case UcfHexScan{value, rest}:
      value

def ucf_hex_scan_rest(x: UcfHexScan) -> String:
  match x:
    case UcfHexScan{value, rest}:
      rest

def ucf_hex_digit(+c: Char) -> Nat:
  +x = Char.to_u32(c)
  ifs(Nat, Bool.and(U32.is_ge(x, 48), U32.is_le(x, 57)),
    u => Nat.sub(U32.to_nat(x), 48n),
    u =>
      ifs(Nat, Bool.and(U32.is_ge(x, 65), U32.is_le(x, 70)),
        v => Nat.add(10n, Nat.sub(U32.to_nat(x), 65n)),
        v => 0n))

def ucf_scan_hex_go(s: String, n: Nat, +acc: Nat) -> UcfHexScan:
  match s n:
    case u 0n:
      UcfHexScan{U32.from_nat(acc), u}
    case SCon{+h, +t} 1n++p:
      ucf_scan_hex_go(t, p, Nat.add(Nat.mul(acc, 16n), ucf_hex_digit(h)))
    case SNil{} _:
      UcfHexScan{U32.from_nat(acc), SNil{}}

def ucf_scan_hex(+s: String) -> UcfHexScan:
  ucf_scan_hex_go(s, 6n, 0n)

type UcfValueScan is Data:
  UcfValueScan{folded: String, rest: String}

def ucf_value_scan_folded(x: UcfValueScan) -> String:
  match x:
    case UcfValueScan{folded, rest}:
      folded

def ucf_value_scan_rest(x: UcfValueScan) -> String:
  match x:
    case UcfValueScan{folded, rest}:
      rest

def ucf_take_value_finish(s: String, +acc: String) -> UcfValueScan:
  match s:
    case SCon{';', t}:
      UcfValueScan{String.reverse(acc), t}
    case u:
      UcfValueScan{String.reverse(acc), u}

def ucf_take_value_go(s: String, n: Nat, +acc: String) -> UcfValueScan:
  match s n:
    case SNil{} _:
      UcfValueScan{String.reverse(acc), SNil{}}
    case SCon{+h, +t} 1n++p:
      ucf_take_value_go(t, p, SCon{h, acc})
    case SCon{+h, +t} 0n:
      ucf_take_value_finish(t, acc)

def ucf_scan_value(+s: String) -> UcfValueScan:
  match s:
    case SCon{+lench, SCon{':', +aftercolon}}:
      +len = Nat.sub(U32.to_nat(Char.to_u32(lench)), 48n)
      ucf_take_value_go(aftercolon, len, SNil{})
    case u:
      UcfValueScan{SNil{}, u}

type UcfEntryScan is Data:
  UcfEntryScan{code: U32, folded: String, rest: String}

def ucf_entry_scan_code(x: UcfEntryScan) -> U32:
  match x:
    case UcfEntryScan{code, folded, rest}:
      code

def ucf_entry_scan_folded(x: UcfEntryScan) -> String:
  match x:
    case UcfEntryScan{code, folded, rest}:
      folded

def ucf_entry_scan_rest(x: UcfEntryScan) -> String:
  match x:
    case UcfEntryScan{code, folded, rest}:
      rest

def ucf_scan_entry(+s: String) -> UcfEntryScan:
  +hex = ucf_scan_hex(s)
  +value = ucf_scan_value(ucf_hex_scan_rest(hex))
  UcfEntryScan{ucf_hex_scan_value(hex), ucf_value_scan_folded(value), ucf_value_scan_rest(value)}

def ucf_lookup_encoded_go(fuel: Nat, +table: String, +code: U32) -> Maybe<&2, String>:
  match fuel:
    case 0n:
      None{}
    case 1n++f:
      match table:
        case SNil{}:
          None{}
        case SCon{+h0, +t0}:
          +entry = ucf_scan_entry(table)
          +entrycode = ucf_entry_scan_code(entry)
          ifs(Maybe<&2, String>, U32.is_eq(code, entrycode),
            u => Some{ucf_entry_scan_folded(entry)},
            u =>
              ifs(Maybe<&2, String>, U32.is_lt(code, entrycode),
                v => None{},
                v => ucf_lookup_encoded_go(f, ucf_entry_scan_rest(entry), code)))

def ucf_lookup_encoded(+table: String, +code: U32) -> Maybe<&2, String>:
  ucf_lookup_encoded_go(160n, table, code)

'''


def render(entries):
    buckets = defaultdict(list)
    for codepoint, folded in entries:
        buckets[codepoint >> 8].append((codepoint, folded))
    if max(len(items) for items in buckets.values()) >= MAX_BUCKET_ENTRIES:
        raise SystemExit("case-fold bucket exceeds lookup fuel")

    out = [PRELUDE]
    bucket_ids = sorted(buckets)
    for bucket in bucket_ids:
        body = "".join(
            f"{codepoint:06X}{len(folded)}:{bend_escape(folded)};"
            for codepoint, folded in buckets[bucket]
        )
        out.append(f"def unicode_casefold_table_{bucket:04x}() -> String:\n")
        out.append(f"  \"{body}\"\n\n")

    out.append("# Language-independent full case folding of one Unicode scalar.\n")
    out.append("# Gaps scan the next populated bucket and stop at its first entry,\n")
    out.append("# so they correctly report the absence of a mapping.\n")
    out.append("def unicode_casefold_lookup(+code: U32) -> Maybe<&2, String>:\n")

    def chain(index, indent):
        if index == len(bucket_ids):
            return indent + "None{}"
        bucket = bucket_ids[index]
        end = (bucket + 1) * 256
        return (
            f"{indent}ifs(Maybe<&2, String>, U32.is_lt(code, {end}),\n"
            f"{indent}  u => ucf_lookup_encoded(unicode_casefold_table_{bucket:04x}(), code),\n"
            f"{indent}  u =>\n"
            f"{chain(index + 1, indent + '  ')})"
        )

    out.append(chain(0, "  "))
    out.append("\n\n")

    out.append("def unicode_casefold_char(+c: Char) -> String:\n")
    out.append("  maybe_case(String, String, unicode_casefold_lookup(Char.to_u32(c)),\n")
    out.append("    +folded => folded,\n")
    out.append("    u => SCon{c, SNil{}})\n")
    return "".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(ROOT / "src/unicode_casefold.bend"))
    args = parser.parse_args()

    entries = parse(fetch())
    output = Path(args.output)
    output.write_text(render(entries), encoding="utf-8")
    print(f"wrote {output} ({len(entries)} case-fold entries)")


if __name__ == "__main__":
    main()
